export const CATALOGUE_MAKES = Object.keys(CATALOGUE);

export const CATALOGUE_COUNT =
  CATALOGUE_MAKES.reduce((n, k) => n + CATALOGUE[k].length, 0);

/* Flat index: normalised "make model" -> entry, built once on demand. */
let _index = null;
export function catIndex() {
  if (_index) return _index;
  _index = new Map();
  for (const make of CATALOGUE_MAKES) {
    for (const row of CATALOGUE[make]) {
      const [model, y0, y1, type, rarity] = row;
      _index.set(norm(`${make} ${model}`), { make, model, y0, y1, type, rarity });
    }
  }
  return _index;
}

export function norm(s) {
  return String(s || '')
    .toLowerCase()
    .replace(/[()\[\]{}.,\/·]/g, ' ')
    .replace(/[^a-z0-9+\- ]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

/* Strip a trailing generation code so "911 (993)" also matches "911". */
export function baseModel(model) {
  return String(model || '').replace(/\s*\([^)]*\)\s*$/, '').trim();
}

/* Best-effort lookup of a user-typed make/model against the catalogue.
   Tries exact match, then generation-stripped, then prefix. */
export function lookup(make, model) {
  if (!make && !model) return null;
  const idx = catIndex();
  const full = norm(`${make} ${model}`);
  if (idx.has(full)) return idx.get(full);

  const rows = CATALOGUE[make];
  if (rows) {
    const nm = norm(model);
    if (!nm) return null;
    let best = null;
    for (const row of rows) {
      const rm = norm(row[0]);
      const rb = norm(baseModel(row[0]));
      if (rm === nm || rb === nm) {
        best = { make, model: row[0], y0: row[1], y1: row[2], type: row[3], rarity: row[4] };
        break;
      }
      if (!best && (rm.startsWith(nm + ' ') || nm.startsWith(rb + ' ')) && nm.length > 2) {
        best = { make, model: row[0], y0: row[1], y1: row[2], type: row[3], rarity: row[4] };
      }
    }
    return best;
  }
  return null;
}
